#!/usr/bin/env node
/**
 * Generates seed vocabulary SQL from aligned triples (EN, RU, SR).
 * Run: node scripts/generate-seed-sql.mjs           → 003_seed_vocabulary.sql (from seed-triples.json)
 * Run: node scripts/generate-seed-sql.mjs --additional → 005_seed_vocabulary_expanded.sql (from seed-triples-additional.json)
 * Each triple becomes 6 rows (all directions for EN↔RU, EN↔SR, RU↔SR). See docs/SEED_AND_LOOKUP_STRATEGY.md §1.
 */

import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const isAdditional = process.argv.includes('--additional')
const triplesPath = join(root, 'scripts', isAdditional ? 'seed-triples-additional.json' : 'seed-triples.json')
const outPath = join(root, 'docs', 'supabase-migrations', isAdditional ? '005_seed_vocabulary_expanded.sql' : '003_seed_vocabulary.sql')

function escapeSql (str) {
  return str.replace(/'/g, "''")
}

const triples = JSON.parse(readFileSync(triplesPath, 'utf-8'))
const rows = []

for (const { en, ru, sr } of triples) {
  const pairs = [
    [en, ru, 'en', 'ru'],
    [ru, en, 'ru', 'en'],
    [en, sr, 'en', 'sr'],
    [sr, en, 'sr', 'en'],
    [ru, sr, 'ru', 'sr'],
    [sr, ru, 'sr', 'ru'],
  ]
  for (const [word, translation, langFrom, langTo] of pairs) {
    rows.push(`  ('${escapeSql(word)}', '${escapeSql(translation)}', '${langFrom}', '${langTo}', 'app')`)
  }
}

const comment = isAdditional
  ? '-- Additional app library vocabulary (aligned triples). Run after 003_seed_vocabulary.sql.'
  : '-- Seed app library vocabulary from aligned triples (EN, RU, SR). Run after 002_core_data_layer.sql.'
const sql = `-- ${comment}
-- Generated by: node scripts/generate-seed-sql.mjs${isAdditional ? ' --additional' : ''}
-- Source: ${isAdditional ? 'scripts/seed-triples-additional.json' : 'scripts/seed-triples.json'}
-- See docs/SEED_AND_LOOKUP_STRATEGY.md §1.

insert into public.vocabulary (word, translation, language_from, language_to, source)
values
${rows.join(',\n')};
`

writeFileSync(outPath, sql, 'utf-8')
console.log(`Wrote ${rows.length} rows to ${outPath}`)
