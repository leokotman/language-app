#!/usr/bin/env node
/**
 * Generates docs/supabase-migrations/003_seed_vocabulary.sql from scripts/seed-triples.json.
 * Run: node scripts/generate-seed-sql.mjs
 * Each triple (en, ru, sr) becomes 6 vocabulary rows (all directions for EN↔RU, EN↔SR, RU↔SR).
 * See docs/SEED_AND_LOOKUP_STRATEGY.md §1.
 */

import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const triplesPath = join(root, 'scripts', 'seed-triples.json')
const outPath = join(root, 'docs', 'supabase-migrations', '003_seed_vocabulary.sql')

function escapeSql (str) {
  return str.replace(/'/g, "''")
}

const triples = JSON.parse(readFileSync(triplesPath, 'utf-8'))
const rows = []

for (const { en, ru, sr } of triples) {
  const pairs = [
    [en, ru, 'en', 'ru'],
    [ru, en, 'ru', 'en'],
    [en, sr, 'en', 'sr'],
    [sr, en, 'sr', 'en'],
    [ru, sr, 'ru', 'sr'],
    [sr, ru, 'sr', 'ru'],
  ]
  for (const [word, translation, langFrom, langTo] of pairs) {
    rows.push(`  ('${escapeSql(word)}', '${escapeSql(translation)}', '${langFrom}', '${langTo}', 'app')`)
  }
}

const sql = `-- Seed app library vocabulary from aligned triples (EN, RU, SR).
-- Generated by: node scripts/generate-seed-sql.mjs
-- Source: scripts/seed-triples.json
-- See docs/SEED_AND_LOOKUP_STRATEGY.md §1. Run after 002_core_data_layer.sql.

insert into public.vocabulary (word, translation, language_from, language_to, source)
values
${rows.join(',\n')};
`

writeFileSync(outPath, sql, 'utf-8')
console.log(`Wrote ${rows.length} rows to ${outPath}`)
